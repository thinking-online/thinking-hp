def load(no):
    t = io.open(V + no + ".md", encoding="utf-8").read()
    heads = [h for h in re.findall(r"^## (.+)$", t, flags=re.M) if h not in FIX]
    kyou = re.findall(r"^今日やること　(.+)$", t, flags=re.M)
    s = io.open(V + "_steps/" + no + ".md", encoding="utf-8").read()
    steps = re.findall(r"^### (STEP 0\d)　(.+)$", s, flags=re.M)
    kijun = re.findall(r"「できた」の基準　+(.+)$", s, flags=re.M)
    return heads, (kyou[-1] if kyou else ""), steps, (kijun[0] if kijun else "")

