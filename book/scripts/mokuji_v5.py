def text():
    out = [v4.HEAD, ""]
    col = {}
    for c in v4.COL: col.setdefault(c[0], []).append(c)
    for no, title, tag in v4.CH:
        out += [f"{no}　{title}　〔{tag}〕", ""]
        a, b = v4.RANGE[no]
        for i in range(a, b + 1):
            n = "%02d" % i
            x, o = PAIR[n]
            if n in v4.LAW:
                out += [f"絶対法則{n}　{v4.LAW[n]}", f"　× {x}", f"　○ {o}"]
            else:
                out += [f"{n}　× {x}", f"　　○ {o}"]
            for _, kind, ct, sub, _f in col.get(n, []):
                out += [f"　【{kind}】{ct}"]
        out.append("")
    return "\n".join(out).rstrip() + "\n"

if __name__ == "__main__":
    assert len(PAIR) == 50
    print(text(), end="")
