LIM = (24, 14, 36)


def n(s):
    return len(re.sub(r"\s", "", s))


def over(kk):
    t, steps, king = S[kk]
    return any(n(h) > LIM[0] or n(v) > LIM[1] for h, v in steps) or n(king) > LIM[2]


if __name__ == "__main__":
    assert len(S) == 50 and all(len(v[1]) == 3 for v in S.values())
    if "--check" in sys.argv:
        bad = 0
        for kk, (t, steps, king) in sorted(S.items()):
            for i, (h, v) in enumerate(steps):
                if n(h) > LIM[0] or n(v) > LIM[1]:
                    bad += 1; print(kk, "STEP0%d" % (i + 1), n(h), n(v), h, "｜", v)
            if n(king) > LIM[2]:
                bad += 1; print(kk, "基準", n(king), king)
        print("枠より長いもの", bad)
    elif "--html" in sys.argv:
        import step_card_html
        step_card_html.build2(S, CH, NOTE, SRC, over)
