    if "--check" in sys.argv:
        n_bad = 0
        for n in sorted(C):
            for who, (big, small) in zip(("伸", "頭"), C[n]):
                if len(strip(big)) > 8 or len(small) > 14 or overlap(big, small):
                    n_bad += 1; print(n, who, big, len(strip(big)), "｜", small, len(small), overlap(big, small)[:1])
        print("直しが要るもの", n_bad)
